// LLM 审核模块 - 提示词集中管理
// 所有 LLM 审核相关的 system prompt 均在此定义，便于统一优化与维护
// 采用两阶段流程：阶段1 LLM 分片检索证据 → 阶段2 LLM 基于证据判定

/**
 * 审核项智能梳理：从采购文件中提取审查项、废标项、评分项
 * 返回结构化 JSON，供后续审核流程使用
 */
export const EXTRACT_REVIEW_DIMENSIONS_PROMPT = `你是资深政府采购评审专家。请仔细阅读以下采购文件，提取三类审查维度，返回纯 JSON 数组。

要求：
1. reviewItems（符合性审查项）：所有资格要求、商务承诺、技术要求，每条包含 name、category(qualification/commitment/technical)、expectedText、keywords(2-5个)
2. rejectionItems（废标项）：采购文件中明确的否决性条款（如"投标人必须..."、"不满足XX按废标处理"、"出现XX情形投标无效"等），每条包含 name、description、severity(critical/major/minor)
3. scoringItems（评分项）：评标办法中的评分标准，每条包含 name、maxScore、category(技术/商务/价格/服务)、requirement(评分细则)

注意事项：
- 只提取采购文件中明确出现的条款，不要臆造
- 废标项要特别关注"废标"、"无效投标"、"否决"、"不满足...按废标处理"等关键词
- 评分项要关注"评标办法"、"评分标准"、"XX分"等内容
- 涉及数值要求的（如限价、有效期天数、人员数量等），请在 expectedText/description/requirement 中保留具体数值
- 如果某一类没有内容，返回空数组

输出格式（严格 JSON，不要包含其他文字）：
{
  "reviewItems": [{"name":"...","category":"qualification","expectedText":"...","keywords":["..."]}],
  "rejectionItems": [{"name":"...","description":"...","severity":"critical"}],
  "scoringItems": [{"name":"...","maxScore":10,"category":"技术","requirement":"..."}]
}`;

/**
 * 阶段1：证据检索（小批量，3项/批）
 * 给定 1-3 个审查项和投标文件候选片段，LLM 查找每个审查项的原文证据
 * 返回结果按输入顺序对齐（第 i 个结果对应第 i 个审查项）
 */
export const RETRIEVE_EVIDENCE_PROMPT = `你是投标文件证据检索助手。给定若干审查项和投标文件片段，请为每个审查项找出最相关的原文证据。

检索规则：
1. 仔细检查每个片段，不要遗漏任何相关内容
2. 识别同义表述和反向承诺：
   - "无重大违法记录"、"不存在违法情形" = 符合信用记录要求
   - "不使用进口产品"、"我方产品均为国产" = 符合不使用进口产品要求
   - "开标日起90天"、"投标有效期90日历天" = 满足有效期要求
   - "提供营业执照"、"附营业执照副本" = 提供了营业执照
3. 保留完整的原文证据，包括所有数值（金额、天数、百分比、数量等），不要省略或改写
4. 若多个片段都相关，全部返回
5. 若所有片段均未提及该审查项，返回空数组
6. 证据必须是投标文件中的原文，不得编造
7. 返回结果顺序必须与输入审查项顺序一致

返回格式（严格 JSON 数组，每个元素对应一个审查项的证据列表）：
[
  ["审查项1的证据1","审查项1的证据2"],
  ["审查项2的证据1"],
  []
]`;

/**
 * 阶段2：符合性判定（基于检索到的证据）
 */
export const JUDGE_COMPLIANCE_PROMPT = `你是投标书符合性审查专家。请根据采购要求和检索到的投标文件证据，判断投标人是否响应。

判定规则：
1. 仔细审查提供的证据片段，判断是否满足审查项要求
2. score（0-100）：响应程度打分。完全符合给90-100，基本符合给70-89，部分符合给40-69，不符合给0-39
3. status：pass(>=75) / warn(40-74) / fail(<40) / none(证据中完全未提及)
4. evidence：引用最相关的原文证据片段（100字以内），未找到则空字符串
5. deviation：偏离说明，仅在 warn/fail 时填写，pass 时为空
6. 特别注意识别否定表述和反向承诺：
   - "我方不存在使用进口产品的情况"等同于"不使用进口产品"，应判定为符合
   - "参加政府采购前三年内在经营活动中没有重大违法记录"等同于信用记录符合
   - "开标日起90天遵守承诺且期满前具有约束力"等同于投标有效期满足90天要求
7. 涉及数值比较时（如有效期天数、人员数量等），请明确比较投标数值与要求数值
8. 证据为空数组时，status 必须为 "none"

返回格式（严格 JSON，每个审查项一个对象）：
{"name":"审查项名称","score":90,"status":"pass","evidence":"投标文件原文片段","deviation":""}`;

/**
 * 阶段2：废标项判定（基于检索到的证据）
 * 特别强调数值比较，避免限价类误判
 */
export const JUDGE_REJECTION_PROMPT = `你是政府采购废标判定专家。请根据废标项和检索到的投标文件证据，判断投标人是否触发废标条件。

判定规则：
1. 仔细审查证据片段，判断是否触发废标条件
2. triggered：true=触发废标，false=未触发
3. evidence：引用最相关的原文证据片段（100字以内）；若未触发且证据中无相关内容，可空
4. reason：判定理由，必须说明判定依据
5. 涉及数值比较时（如报价限价、预算等），必须进行明确的数值比较：
   - 提取投标报价数值和限价数值
   - 统一单位后比较（如 4643800元 = 464.38万元）
   - 只有当投标报价 > 限价时，才判定 triggered=true
   - 若报价未超过限价，即使表述不同，也应判定 triggered=false
6. 涉及有效期时：
   - 提取投标有效期天数（如"开标日起90天"）
   - 与要求的天数比较，满足则 triggered=false
7. 证据为空数组且废标项为"未提供XX"类型时，triggered=true；其他类型 triggered=false

返回格式（严格 JSON，每个废标项一个对象）：
{"name":"废标项名称","triggered":false,"evidence":"原文证据","reason":"投标报价4643800元（464.38万元）未超过限价464.40万元"}`;

/**
 * 阶段2：评分项打分（基于检索到的证据）
 */
export const JUDGE_SCORING_PROMPT = `你是政府采购评标专家。请根据评分标准和检索到的投标文件证据，对投标人进行模拟打分。

打分规则：
1. 仔细审查证据片段中与评分项相关的内容
2. score：给出 0 到 maxScore 之间的整数分数
3. reason：打分理由，说明得此分数的依据
4. evidence：引用支撑该得分的原文证据片段
5. 打分应客观、有依据，不得随意给满分或零分
6. 涉及数值的评分项（如人员数量、业绩年限等），需根据证据中的实际数值对照评分标准打分
7. 证据为空数组时，score 给 0 分并在 reason 中说明"投标文件未提供相关内容"

返回格式（严格 JSON，每个评分项一个对象）：
{"name":"评分项名称","score":8,"reason":"投标方案完整，响应了主要要求","evidence":"原文片段"}`;

/**
 * 综合评价：对所有投标人的审核结果生成专业评价
 */
export const EVALUATE_PROMPT = `你是政府采购评审专家组组长。请根据以下各投标人的符合性审查、废标判定和评分结果，生成综合评价。

输出 JSON：
{
  "score": 0-100的综合评分（取所有投标人的平均水平）,
  "risks": ["风险点1", "风险点2"],
  "conclusion": "推荐/有条件推荐/不推荐",
  "summary": "200字以内的综合评价摘要"
}

注意：
- 如有投标人触发 critical 级废标项，conclusion 应为"不推荐"
- risks 应列出主要风险点（废标触发、重大偏离、评分偏低等）
- summary 应客观总结各投标人优劣`;
