/**
 * 审核事实基准（运行时注入，最高优先级）
 * 关键作用：消除模型"不知道今天日期"导致的未来日期/年份幻觉
 */
export function buildAuditContext(meta?: ProjectMeta | null): string {
  const now = new Date();
  const week = ["日", "一", "二", "三", "四", "五", "六"][now.getDay()];
  const today = `${now.getFullYear()} 年 ${now.getMonth() + 1} 月 ${now.getDate()} 日（星期${week}）`;
  const deadline = meta?.bidDeadline?.trim() || "采购文件未明确给出（禁止臆测具体日期）";
  return `【审核事实基准 · 最高优先级，必须严格遵守】
1. 今天的真实日期是 ${today}。凡涉及"现在/当前/今年/近年/未来/逾期/有效期内/日期晚于或早于今天"的判断，一律以该日期为唯一基准；严禁使用你训练数据或记忆中的年份当作"当前年份"。
2. 采购文件载明的投标截止/开标时间：${deadline}。
3. 日期类判定规则：
   - 只有证据中的日期确实晚于"今天"，才能称为"未来日期"；不晚于今天的日期严禁称为未来日期。
   - 只有证据日期与投标截止时间存在明确先后矛盾时，才能判定时效违规；投标截止时间未知时，一律不得判定时效违规。
   - 无法确认日期先后关系时，不得产出 critical/major 问题，应输出 riskLevel=info 并说明"日期时效需人工核验"。
4. 证据中未出现的事实（日期、数值、名称、页码、条款号）一律禁止编造、推测或凭经验补全；页码无法从原文确认时必须留空。`;
}

